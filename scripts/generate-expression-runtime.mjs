// Generates src/project/expressionRuntime.generated.ts: the expression engine as plain JavaScript text for
// exported prototypes (published HTML and the React export). It is produced from the one TypeScript engine in
// src/project/expressions.ts, so a fix made there reaches exports too (B20). Before this, the exports carried
// a second, hand-written copy that had already drifted from the engine.
//
// Run after changing src/project/expressions.ts:
//   npm run generate:expression-runtime
// The unit tests fail if the committed file is out of date.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const EXPRESSION_SOURCE_FILE = "src/project/expressions.ts";
export const EXPRESSION_RUNTIME_OUTPUT = "src/project/expressionRuntime.generated.ts";
// The only names the exported runtime exposes; everything else stays private inside it, so it cannot clash
// with the names in the page or component it is pasted into.
const EXPOSED = ["evaluateExpression", "clearExpressionCache"];

/** The engine as a self-contained piece of JavaScript that declares `evaluateExpression` and `clearExpressionCache`. */
export function generateEngineScript(rootDir = root) {
  const text = fs.readFileSync(path.join(rootDir, EXPRESSION_SOURCE_FILE), "utf8");
  const { outputText } = ts.transpileModule(text, {
    fileName: EXPRESSION_SOURCE_FILE,
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.ESNext,
      removeComments: true,
      newLine: ts.NewLineKind.LineFeed,
    },
  });
  // Plain script, not a module: drop `export` from the top-level declarations.
  const script = outputText.replace(/^export (?=(?:async )?(?:function|const|let|var|class)\b)/gm, "");
  if (/^\s*(?:import|export)\b/m.test(script)) {
    throw new Error(`${EXPRESSION_SOURCE_FILE} has an import or export the generator does not handle.`);
  }
  // The text is inlined into an HTML <script>, so it must not be able to end it.
  if (/<\/script|<!--/i.test(script)) {
    throw new Error(`${EXPRESSION_SOURCE_FILE} contains text that is not safe inside an inline <script>.`);
  }
  for (const name of EXPOSED) {
    if (!new RegExp(`^function ${name}\\b`, "m").test(script)) {
      throw new Error(`${EXPRESSION_SOURCE_FILE} no longer exports ${name}().`);
    }
  }
  const names = EXPOSED.join(", ");
  return `const { ${names} } = (() => {\n${script.trimEnd()}\nreturn { ${names} };\n})();\n`;
}

function asTemplateLiteralText(value) {
  return value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

/** The full contents of src/project/expressionRuntime.generated.ts. */
export function generateExpressionRuntimeSource(rootDir = root) {
  return [
    `// Generated by scripts/generate-expression-runtime.mjs from ${EXPRESSION_SOURCE_FILE}; do not edit by hand.`,
    "// Change the engine in expressions.ts, then run: npm run generate:expression-runtime",
    "// The unit tests fail if this file is out of date.",
    "",
    `export const EXPRESSION_RUNTIME_SOURCE = \`\n${asTemplateLiteralText(generateEngineScript(rootDir))}\`;`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
  const outputPath = path.join(root, EXPRESSION_RUNTIME_OUTPUT);
  const next = generateExpressionRuntimeSource();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
    if (current !== next) {
      console.error(`${EXPRESSION_RUNTIME_OUTPUT} is out of date. Run: npm run generate:expression-runtime`);
      process.exit(1);
    }
    console.log(`${EXPRESSION_RUNTIME_OUTPUT} is up to date.`);
  } else {
    fs.writeFileSync(outputPath, next);
    console.log(`Wrote ${EXPRESSION_RUNTIME_OUTPUT} (${next.split("\n").length} lines).`);
  }
}
