export const CANVAS_ICON_NAMES = Object.keys(CANVAS_ICON_LIBRARY);

export function renderCanvasIconSvg(
  name: string,
  color: string,
  strokeWidth: number,
): string {
  const Icon = CANVAS_ICON_LIBRARY[name] ?? CANVAS_ICON_LIBRARY.Star;
  const svg = renderToStaticMarkup(
    createElement(Icon, {
      width: 24,
      height: 24,
      color,
      stroke: color,
      strokeWidth,
      fill: "none",
    }),
  );
  return svg.replaceAll("currentColor", color);
}
